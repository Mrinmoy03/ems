/**
 * Returns available years for reporting and timesheets.
 * In a fresh deployment without history, only the current active year is present.
 * Previous years appear only when historical month records exist.
 * Upcoming/future years never appear until that calendar year arrives.
 */
export const getAvailableYears = (currentYear: number = new Date().getFullYear()): number[] => {
  const years = new Set<number>()
  years.add(currentYear)
  availableMonths.forEach(m => {
    if (m.year <= currentYear) {
      years.add(m.year)
    }
  })
  return Array.from(years).sort((a, b) => b - a)
}

export const getMonthsForYear = (year: number): MonthOption[] => {
  return availableMonths.filter(m => m.year === year)
}

export const getYearAndMonthFromKey = (monthKey: string): { year: number; monthKey: string } => {
  const found = availableMonths.find(m => m.key === monthKey)
  if (found) {
    return { year: found.year, monthKey }
  }
  const parts = monthKey.split("-")
  const parsedYear = parseInt(parts[0], 10) || new Date().getFullYear()
  return { year: parsedYear, monthKey }
}

export const getLatestMonthForYear = (year: number): string => {
  const months = getMonthsForYear(year)
  return months[0]?.key || `${year}-12`
}

/**
 * Returns the active month key dynamically (e.g. "2026-10").
 * Dynamically resolves against available months, preventing hardcoded period failures.
 */
export const getCurrentMonthKey = (): string => {
  const now = new Date()
  const realKey = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`
  if (mockMonthsData[realKey]) {
    return realKey
  }
  return availableMonths[0]?.key || realKey
}

/**
 * Safely retrieves MonthData for a given monthKey with dynamic fallback.
 * Backend-ready: avoids undefined crashes if requested period is not yet present.
 */
export const getMonthData = (monthKey?: string): MonthData => {
  const key = monthKey || getCurrentMonthKey()
  if (mockMonthsData[key]) {
    return mockMonthsData[key]
  }
  const defaultKey = getCurrentMonthKey()
  if (mockMonthsData[defaultKey]) {
    return mockMonthsData[defaultKey]
  }
  const [yrStr, moStr] = key.split("-")
  const yr = parseInt(yrStr, 10) || new Date().getFullYear()
  const moNum = parseInt(moStr, 10) || (new Date().getMonth() + 1)
  const monthName = new Date(yr, moNum - 1, 1).toLocaleString("en-US", { month: "long" })
  return {
    monthKey: key,
    monthName,
    year: yr,
    summary: {
      month: monthName,
      year: yr,
      workingDays: 20,
      daysPresent: 0,
      totalHoursWorked: 0,
      tasksCompleted: 0,
      completionRate: 100,
      averageCompletionHours: 0,
    },
    workingDays: [],
    eodReports: [],
  }
}

