const now = new Date()

// Helper to construct today's deadlines easily
const getTodayAt = (hours: number, minutes = 0) => {
  const d = new Date(now)
  d.setHours(hours, minutes, 0, 0)
  return d.toISOString()
}

// Relative timestamp helpers
